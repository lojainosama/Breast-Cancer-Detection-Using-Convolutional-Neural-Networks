import os
import numpy as np
import pandas as pd
import tensorflow as tf
import matplotlib.pyplot as plt
import seaborn as sns

from tensorflow.keras import layers, models, callbacks
from sklearn.model_selection import train_test_split
from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import classification_report, confusion_matrix

# ===============================
# 1️⃣ Load Dataset
# ===============================

DATASET_PATH = "IDC_regular_ps50_idx5"

image_paths, labels, patient_ids = [], [], []

for patient in os.listdir(DATASET_PATH):
    patient_path = os.path.join(DATASET_PATH, patient)
    if not os.path.isdir(patient_path):
        continue
    for cls in ['0', '1']:
        class_path = os.path.join(patient_path, cls)
        if os.path.isdir(class_path):
            for img in os.listdir(class_path):
                if img.endswith(".png"):
                    image_paths.append(os.path.join(class_path, img))
                    labels.append(int(cls))
                    patient_ids.append(patient)

df = pd.DataFrame({
    "image_path": image_paths,
    "label": labels,
    "patient_id": patient_ids
})

print("Total images:", len(df))
print("Class distribution:\n", df['label'].value_counts())

# ===============================
# 2️⃣ Patient-wise Split (NO Leakage)
# ===============================

patients_df = df[['patient_id', 'label']].drop_duplicates('patient_id')

train_pat, temp_pat = train_test_split(
    patients_df,
    test_size=0.2,
    stratify=patients_df['label'],
    random_state=42
)

val_pat, test_pat = train_test_split(
    temp_pat,
    test_size=0.5,
    stratify=temp_pat['label'],
    random_state=42
)

train_df = df[df['patient_id'].isin(train_pat['patient_id'])]
val_df   = df[df['patient_id'].isin(val_pat['patient_id'])]
test_df  = df[df['patient_id'].isin(test_pat['patient_id'])]

print("\nAfter patient split:")
print("Train:\n", train_df['label'].value_counts())
print("Val:\n", val_df['label'].value_counts())
print("Test:\n", test_df['label'].value_counts())

# ===============================
# 3️⃣ tf.data Pipeline
# ===============================

IMG_SIZE = (50, 50)
BATCH_SIZE = 32

def load_image(path, label):
    img = tf.io.read_file(path)
    img = tf.image.decode_png(img, channels=3) #convert the file into image
    img = tf.image.resize(img, IMG_SIZE)      #make them with one size
    img = tf.cast(img, tf.float32) / 255.0   # convert the pixel from (0-255) into (0-1)
    return img, label

def make_dataset(df, shuffle=False):
    ds = tf.data.Dataset.from_tensor_slices((df['image_path'], df['label']))  #there is no open for images, just the name of image and its type.   from_tensor_slices--> get the the images name
    ds = ds.map(load_image, num_parallel_calls=tf.data.AUTOTUNE)  #open images
    if shuffle:
        ds = ds.shuffle(1000)
    return ds.batch(BATCH_SIZE).prefetch(tf.data.AUTOTUNE)

train_ds = make_dataset(train_df, shuffle=True)
val_ds   = make_dataset(val_df)
test_ds  = make_dataset(test_df)

# ===============================
# 4️⃣ Handle Class Imbalance
# ===============================

class_weights = compute_class_weight(
    class_weight='balanced',
    classes=np.array([0,1]),
    y=train_df['label']
)
class_weights = dict(enumerate(class_weights))

print("\nClass Weights:", class_weights)
